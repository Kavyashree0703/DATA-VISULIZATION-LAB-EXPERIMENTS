import kagglehub

# Download latest version
path = kagglehub.dataset_download("START-UMD/gtd")

print("Path to dataset files:", path)

import os
import pandas as pd

print("Dataset path:", path)

print("\nFiles in dataset:")
print(os.listdir(path))

# Find CSV file automatically
csv_file = [f for f in os.listdir(path) if f.endswith(".csv")][0]

print("\nCSV file:", csv_file)

# Load dataset
df = pd.read_csv(
    os.path.join(path, csv_file),
    encoding="latin1",
    low_memory=False
)

print("\nFirst 5 rows:")
display(df.head())

print("\nLast 5 rows:")
display(df.tail())

print("\nDataset information:")
df.info()

print("\nShape:")
print(df.shape)

print("\nColumns:")
print(df.columns.tolist())

print("\nData types:")
print(df.dtypes)

print("\nStatistical description:")
display(df.describe())

print("\nMissing values:")
display(df.isnull().sum())

print("\nTop 10 countries:")
display(df["country_txt"].value_counts().head(10))

print("\nRegions:")
display(df["region_txt"].value_counts())

print("\nAttack types:")
display(df["attacktype1_txt"].value_counts())

print("\nUnique attack types:")
print(df["attacktype1_txt"].unique())

print("\nCorrelation:")
display(df.corr(numeric_only=True))

# Excel
df.to_excel("terrorism_data.xlsx", index=False)

# JSON
df.to_json("terrorism_data.json", orient="records", indent=4)

# CSV
df.to_csv("terrorism_data.csv", index=False)

print("\nCSV, Excel and JSON files created successfully.")
